import type {TextOptions} from "@clack/core";
import type {z} from "zod";

// ----------------------------------------------------------------------------------------
// 실제 설정값과 화면 표시를 구분한 초기화 추천값
//
// value: 선택 시 사용할 설정값
// label: 선택 메뉴에 표시할 이름
// hint: 기본 선택이나 후보 출처의 안내
// ----------------------------------------------------------------------------------------
interface InitPreset<T> {
    value: T;
    label: string;
    hint?: string;
}

// ----------------------------------------------------------------------------------------
// Clack이 소유하는 입력 스트림과 취소 신호
// ----------------------------------------------------------------------------------------
type InitPromptConnection = Pick<TextOptions, "input" | "output" | "signal">;

// ----------------------------------------------------------------------------------------
// 질문이 활성화된 동안 보존하는 선택과 입력 버퍼
//
// index: 추천값 또는 마지막 직접 입력 행의 위치
// input: 방향키 이동과 실제 텍스트 수정을 구분하는 직전 입력
// ----------------------------------------------------------------------------------------
export interface InitPromptSelection {
    index: number;
    input: string;
}

// ----------------------------------------------------------------------------------------
// 한 질문 안의 추천값, 직접 입력과 필드 검증
//
// message: 박스 제목으로 표시할 질문
// placeholder: 빈 직접 입력의 예시
// presets: 첫 항목을 기본 선택으로 사용하는 추천값
// schema: 확정 전 검증과 반환값 정규화
// custom: 직접 입력 허용 여부, 미지정 시 허용
// ----------------------------------------------------------------------------------------
export interface InitPromptParams<T> extends InitPromptConnection {
    message: string;
    placeholder?: string;
    presets: readonly InitPreset<T>[];
    schema: z.ZodType<T>;
    custom?: boolean;
}
