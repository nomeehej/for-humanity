import type {DocHeading} from "@/type/doc-heading";
import type {DocSection} from "@/type/doc-section";

// ----------------------------------------------------------------------------------------
// 목차 소제목 항목
//
// heading: 제목 id와 텍스트
// ----------------------------------------------------------------------------------------
interface TocSub {
    heading: DocHeading;
}

// ----------------------------------------------------------------------------------------
// 목차 절과 소제목 목록
//
// part: 이 절에서 시작하는 가름 이름
// subs: 해당 절의 소제목, 현재 위치와 무관하게 전체 표시
// ----------------------------------------------------------------------------------------
export interface TocSection extends TocSub {
    part?: DocSection["part"];
    subs: TocSub[];
}

// ----------------------------------------------------------------------------------------
// 가름별 목차 묶음
//
// part: 묶음 위의 가름 이름, 첫 묶음은 생략 가능
// ----------------------------------------------------------------------------------------
export interface TocGroup {
    part?: DocSection["part"];
    sections: TocSection[];
}
